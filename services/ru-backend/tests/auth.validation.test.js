const assert = require('node:assert/strict');
const test = require('node:test');

const { signOpsToken, signSessionToken, verifySessionToken } = require('../dist/auth');
const { createRussiaApp } = require('../dist/russiaApp');
const {
  loginSchema,
  createTaskSchema,
  updateTaskStatusSchema,
  createUserSchema,
  createSupportThreadSchema,
  createSupportMessageSchema,
} = require('../dist/validation');

const sessionUser = {
  id: 'u1',
  username: 'manager',
  firstName: 'Main',
  lastName: 'Manager',
  fullName: 'Main Manager',
  role: 'manager',
  shopId: null,
  shopName: null,
};

test('signSessionToken/verifySessionToken roundtrip works', () => {
  const token = signSessionToken(sessionUser);
  assert.deepEqual(verifySessionToken(token), sessionUser);
});

test('session tokens preserve assigned shop id for workers', () => {
  const worker = {
    ...sessionUser,
    id: 'worker_1',
    username: 'worker',
    role: 'worker',
    shopId: 'shop_main',
    shopName: null,
  };
  assert.equal(verifySessionToken(signSessionToken(worker)).shopId, 'shop_main');
});

test('ops token generated by RU contains no personal claims', () => {
  const token = signOpsToken(sessionUser);
  const payload = JSON.parse(Buffer.from(token.split('.')[1], 'base64url').toString('utf8'));
  for (const key of ['sub', 'userId', 'username', 'firstName', 'lastName', 'fullName', 'displayName', 'workerId', 'workerDisplayName', 'shopName']) {
    assert.equal(Object.hasOwn(payload, key), false, `${key} must not be present`);
  }
  assert.equal(payload.role, 'manager');
  assert.deepEqual(payload.shopIds, []);
});

test('personal workflow schemas validate expected fields', () => {
  assert.equal(loginSchema.parse({ username: '  Worker.User  ', password: '123456' }).username, 'worker.user');
  assert.equal(createTaskSchema.parse({ title: ' Pack apples ', assigneeId: 'u2' }).title, 'Pack apples');
  assert.equal(updateTaskStatusSchema.parse({ status: 'done', photoConfirmationUrl: 'https://example.com/x.jpg' }).status, 'done');
  assert.equal(createUserSchema.parse({
    username: 'worker.user',
    firstName: 'Ivan',
    lastName: 'Petrov',
    password: 'secret123',
    role: 'worker',
  }).role, 'worker');
  assert.equal(createSupportThreadSchema.parse({
    category: 'technical_failure',
    subject: ' POS terminal issue ',
    body: ' Terminal stopped printing receipts ',
  }).body, 'Terminal stopped printing receipts');
  assert.equal(createSupportMessageSchema.parse({ body: ' Need manager help ' }).body, 'Need manager help');
});

test('Russia app does not expose stock/order/shop routes', async (t) => {
  const server = createRussiaApp().listen(0);
  t.after(() => new Promise((resolve) => server.close(resolve)));
  const { port } = server.address();

  for (const path of ['/api/stock', '/api/orders', '/api/shops']) {
    const response = await fetch(`http://127.0.0.1:${port}${path}`);
    assert.equal(response.status, 404);
  }
});
