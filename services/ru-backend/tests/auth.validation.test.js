const assert = require('node:assert/strict');
const test = require('node:test');

const { signOpsToken, signSessionToken, verifySessionToken } = require('../dist/auth/auth');
const { createOpsTokenForUser } = require('../dist/services/authService');
const { createRussiaApp } = require('../dist/app/russiaApp');
const {
  loginSchema,
  createTaskSchema,
  pushTokenSchema,
  updateTaskStatusSchema,
  createUserSchema,
  checkInStatsQuerySchema,
  updateUserPasswordSchema,
  updateUserSchema,
  createSupportThreadSchema,
  createSupportMessageSchema,
} = require('../dist/http/validation');

const sessionUser = {
  id: 'u1',
  username: 'manager',
  firstName: 'Main',
  lastName: 'Manager',
  fullName: 'Main Manager',
  role: 'manager',
  shopId: null,
  shopName: null,
};

test('signSessionToken/verifySessionToken roundtrip works', () => {
  const token = signSessionToken(sessionUser);
  assert.deepEqual(verifySessionToken(token), sessionUser);
});

test('session tokens preserve assigned shop id for workers', () => {
  const worker = {
    ...sessionUser,
    id: 'worker_1',
    username: 'worker',
    role: 'worker',
    shopId: 'shop_main',
    shopName: null,
  };
  assert.equal(verifySessionToken(signSessionToken(worker)).shopId, 'shop_main');
});

test('ops token generated by RU contains no personal claims', () => {
  const token = signOpsToken(sessionUser);
  const payload = JSON.parse(Buffer.from(token.split('.')[1], 'base64url').toString('utf8'));
  for (const key of ['sub', 'userId', 'username', 'firstName', 'lastName', 'fullName', 'displayName', 'workerId', 'workerDisplayName', 'shopName']) {
    assert.equal(Object.hasOwn(payload, key), false, `${key} must not be present`);
  }
  assert.equal(payload.role, 'manager');
  assert.deepEqual(payload.shopIds, []);
});

test('store tablet receives shop-scoped worker operations access', () => {
  const tablet = {
    ...sessionUser,
    id: 'tablet_1',
    username: 'tablet',
    role: 'store_tablet',
    shopId: 'shop_main',
    shopName: 'Main Shop',
  };
  const token = createOpsTokenForUser(tablet);
  const payload = JSON.parse(Buffer.from(token.split('.')[1], 'base64url').toString('utf8'));

  assert.equal(payload.role, 'worker');
  assert.deepEqual(payload.shopIds, ['shop_main']);
  assert.deepEqual(payload.scopes, ['shops:read', 'stock:read', 'stock:write', 'orders:read', 'orders:write']);
});

test('personal workflow schemas validate expected fields', () => {
  assert.equal(loginSchema.parse({ username: '  Worker.User  ', password: 'admin' }).username, 'worker.user');
  assert.equal(createTaskSchema.parse({ title: ' Pack apples ', assigneeId: 'u2' }).title, 'Pack apples');
  assert.equal(updateTaskStatusSchema.parse({ status: 'done', photoConfirmationUrl: 'https://example.com/x.jpg' }).status, 'done');
  assert.equal(pushTokenSchema.parse({ pushToken: 'ExpoPushToken[abc_123-xyz]' }).pushToken, 'ExpoPushToken[abc_123-xyz]');
  assert.throws(() => pushTokenSchema.parse({ pushToken: 'not-a-push-token' }));
  assert.equal(createUserSchema.parse({
    username: 'worker.user',
    firstName: 'Ivan',
    lastName: 'Petrov',
    password: 'admin',
    role: 'worker',
  }).role, 'worker');
  assert.equal(updateUserSchema.parse({
    username: 'New.Manager',
    firstName: 'New',
    lastName: 'Manager',
    role: 'manager',
    shopId: null,
  }).username, 'new.manager');
  assert.equal(updateUserPasswordSchema.parse({ password: 'admin' }).password, 'admin');
  assert.equal(createSupportThreadSchema.parse({
    category: 'technical_failure',
    subject: ' POS terminal issue ',
    body: ' Terminal stopped printing receipts ',
  }).body, 'Terminal stopped printing receipts');
  assert.equal(createSupportMessageSchema.parse({ body: ' Need manager help ' }).body, 'Need manager help');
  assert.equal(checkInStatsQuerySchema.parse({ from: '2026-05-01', to: '2026-05-31' }).from, '2026-05-01');
  assert.throws(() => checkInStatsQuerySchema.parse({ from: '2026-02-31', to: '2026-05-31' }));
});

test('Russia app does not expose stock/order/shop routes', async (t) => {
  const server = createRussiaApp().listen(0);
  t.after(() => new Promise((resolve) => server.close(resolve)));
  const { port } = server.address();

  for (const path of ['/api/stock', '/api/orders', '/api/shops']) {
    const response = await fetch(`http://127.0.0.1:${port}${path}`);
    assert.equal(response.status, 404);
  }
});
